function convert(type) {
  type = type.trim();
  const optional = type.match(/^Option<(.+)>$/);
  if (optional) return `${convert(optional[1])} | null`;
  const vector = type.match(/^Vec<(.+)>$/);
  if (vector) return `(${convert(vector[1])})[]`;
  if (type === 'String') return 'string';
  if (['i64', 'u64', 'usize'].includes(type)) return 'number';
  if (type === 'bool') return 'boolean';
  if (type === 'serde_json::Value') return 'SplitNode';
  if (references[type]) return references[type];
  throw new Error(`Unmapped Rust boundary type: ${type}`);
}
const lifecycle = workflow.match(/string_enum!\(EnvironmentLifecycle \{([^}]+)\}\);/)?.[1];
const intents = workflow.match(/string_enum!\(PiLifecycleIntent \{([^}]+)\}\);/)?.[1];
function enumValues(block, name) {
  const values = [...(block ?? '').matchAll(/=> "([a-z_]+)"/g)].map((m) => m[1]);
  if (!values.length) throw new Error(`Cannot parse ${name}`);
  return `export type Boundary${name} = ${values.map((v) => `'${v}'`).join(' | ')};`;
}
let output = `// Generated by npm run kanban:contract:generate. Do not edit.\nimport type { SplitNode } from '../types';\nimport type { CardEnvironmentPane, CardEnvironmentIndicator, KanbanCardSummary, KanbanCardDetail, CleanupResource, RuntimeResourceOutcome, EnvironmentCreationOperation, CardCleanupOperation, CardEnvironment } from './types';\n\n${enumValues(lifecycle, 'EnvironmentLifecycle')}\n${enumValues(intents, 'PiLifecycleIntent')}\n`;
for (const [name, selected] of Object.entries(specs)) {
  const body = domain.match(new RegExp(`pub struct ${name} \\{([\\s\\S]*?)\\n\\}`))?.[1];
  if (!body) throw new Error(`Cannot parse Rust ${name}`);
  const fields = [...body.matchAll(/^\s*pub(?:\([^)]*\))?\s+(\w+):\s+([^,\n]+),/gm)];
  const map = new Map(fields.map((m) => [m[1], m[2]]));
  for (const field of selected) if (!map.has(field)) throw new Error(`Missing ${name}.${field}`);
  // The full field list also catches additions to a prioritized DTO, even
  // when the UI deliberately checks only its revision/lifecycle projection.
  output += `\n// Rust ${name}: ${fields.map((m) => `${m[1]}:${m[2].trim()}`).join(', ')}\n`;
  output += `export type Boundary${name} = {\n${selected.map((field) => `  ${field}: ${convert(map.get(field))};`).join('\n')}\n};\n`;
}
// Request shape and response types are part of the same drift check. Tauri
// camelCases these Rust parameters in the frontend invoke argument object.
for (const name of ['kanban_cards', 'kanban_card_snapshot', 'kanban_cleanup_preflight', 'kanban_start_environment', 'kanban_cleanup_environment_creation', 'kanban_apply_pi_lifecycle_intent', 'kanban_close_card', 'kanban_retry_runtime_cleanup']) {
  const signature = commands.match(new RegExp(`pub (?:async )?fn ${name}\\(([\\s\\S]*?)\\)\\s*->\\s*([^\\{]+)\\{`));
  if (!signature) throw new Error(`Cannot parse Rust command ${name}`);
  output += `// Command ${name}(${signature[1].replace(/\s+/g, ' ').trim()}): ${signature[2].replace(/\s+/g, ' ').trim()}\n`;
  const parameters = [...signature[1].matchAll(/(?:^|,)\s*(\w+):\s+(String|i64|bool|Option<[^>]+>|PiThread|PiLifecycleIntent)(?=,|\s*$)/g)]
    .filter((m) => !['state', 'service', 'app', 'pi_registry', 'pty_registry'].includes(m[1]));
  const camel = (value) => value.replace(/_([a-z])/g, (_, letter) => letter.toUpperCase());
  output += `export type BoundaryRequest_${name} = { ${parameters.map((m) => {
    const optional = m[2].trim().match(/^Option<(.+)>$/);
    return `${camel(m[1])}${optional ? '?' : ''}: ${convert(optional ? optional[1] : m[2])}`;
  }).join('; ')} };\n`;
}
// Bidirectional checks catch optional-vs-null and enum narrowing, not just missing keys.
output += `\ntype Equal<A, B> = (<T>() => T extends A ? 1 : 2) extends (<T>() => T extends B ? 1 : 2) ? true : false;\ntype Assert<T extends true> = T;\n`;
const checked = {
  CardEnvironment: 'CardEnvironment', EnvironmentCreationOperation: 'EnvironmentCreationOperation', CardCleanupOperation: 'CardCleanupOperation',
  KanbanCardSummary: 'KanbanCardSummary', KanbanCard: 'KanbanCardDetail', BoardSnapshot: 'BoardSnapshot',
  BoardChange: 'BoardChange', CardSnapshot: 'CardSnapshot', CleanupPreflight: 'CleanupPreflight', CardRuntimeCleanupResult: 'CardRuntimeCleanupResult',
};
output = output.replace("import type { CardEnvironmentPane,", "import type { BoardSnapshot, BoardChange, CardSnapshot, CleanupPreflight, CardRuntimeCleanupResult, CardEnvironmentPane,");
for (const [name, ts] of Object.entries(checked)) {
  // Existing UI fixtures omit nullable operation fields; the wire itself always
  // sends them. Required preserves their value type while checking nullability.
  const actual = `Required<Pick<${ts}, keyof Boundary${name}>>`;
  output += `type Check${name} = Assert<${['EnvironmentCreationOperation', 'CardCleanupOperation', 'CleanupPreflight'].includes(name)
    ? `${actual} extends Boundary${name} ? true : false`
    : `Equal<${actual}, Boundary${name}>`}>;\n`;
}
output += `type CheckIntent = Assert<Equal<import('./types').PiLifecycleIntent, BoundaryPiLifecycleIntent>>;\n`;
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw new Error('Stale Kanban boundary contract: run npm run kanban:contract:generate');
  console.log('Kanban boundary DTOs match Rust.');
} else fs.writeFileSync(target, output);
